"""R02-01 string-only JSON wire contracts. Run from any directory; no dependencies."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'schema/remote-v1.json').read_text())
out=root/'generated';out.mkdir(exist_ok=True)
rust='// Generated by lom-protocol/tools/generate-remote.py. Do not edit.\n'
kt='// Generated by lom-protocol/tools/generate-remote.py. Do not edit.\npackage top.heang.lom.remote\n'
ts='// Generated by lom-protocol/tools/generate-remote.py. Do not edit.\n'
for name,fields in schema.items():
 rust+='#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct '+name+' {\n'+''.join('    pub '+f+': String,\n' for f in fields)+'}\n'
 kt+='data class '+name+'('+', '.join('val '+f+': String' for f in fields)+')\n'
 ts+='export interface '+name+' { '+''.join(f+': string; ' for f in fields)+'}\n'
for ext,data in [('rs',rust),('kt',kt),('ts',ts)]: (out/('remote_v1.'+ext)).write_text(data)
